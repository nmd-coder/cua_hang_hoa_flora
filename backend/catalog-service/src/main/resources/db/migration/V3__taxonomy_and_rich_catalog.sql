-- Taxonomy: occasions, flower types, colors, dimensions, and rich catalog data

ALTER TABLE categories ADD COLUMN IF NOT EXISTS description TEXT;
ALTER TABLE products ADD COLUMN IF NOT EXISTS weight_g INTEGER DEFAULT 500;
ALTER TABLE products ADD COLUMN IF NOT EXISTS length_cm INTEGER DEFAULT 30;
ALTER TABLE products ADD COLUMN IF NOT EXISTS width_cm INTEGER DEFAULT 25;
ALTER TABLE products ADD COLUMN IF NOT EXISTS height_cm INTEGER DEFAULT 45;
ALTER TABLE products ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ NOT NULL DEFAULT now();

CREATE TABLE IF NOT EXISTS occasions (
    id UUID PRIMARY KEY,
    name TEXT NOT NULL,
    slug TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS product_occasions (
    product_id UUID NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    occasion_id UUID NOT NULL REFERENCES occasions(id) ON DELETE CASCADE,
    PRIMARY KEY(product_id, occasion_id)
);

CREATE TABLE IF NOT EXISTS flower_types (
    id UUID PRIMARY KEY,
    name TEXT NOT NULL,
    slug TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS product_flower_types (
    product_id UUID NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    flower_type_id UUID NOT NULL REFERENCES flower_types(id) ON DELETE CASCADE,
    PRIMARY KEY(product_id, flower_type_id)
);

CREATE TABLE IF NOT EXISTS colors (
    id UUID PRIMARY KEY,
    name TEXT NOT NULL,
    hex_code TEXT
);

CREATE TABLE IF NOT EXISTS product_colors (
    product_id UUID NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    color_id UUID NOT NULL REFERENCES colors(id) ON DELETE CASCADE,
    PRIMARY KEY(product_id, color_id)
);

